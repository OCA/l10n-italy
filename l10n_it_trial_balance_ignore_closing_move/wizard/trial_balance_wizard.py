from odoo import fields, models


class TrialBalanceReportWizard(models.TransientModel):
    _inherit = "trial.balance.report.wizard"

    ignore_closing_move = fields.Boolean(
        string="Ignore closing and opening moves",
        default=True,
        help="Exclude the moves generated by the fiscal year closing procedure "
        "(closing, profit & loss, opening and other closing moves).",
    )

    def _prepare_report_data(self):
        res = super()._prepare_report_data()
        res["ignore_closing_move"] = self.ignore_closing_move
        return res
